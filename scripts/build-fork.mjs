import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = new URL("../dist/spicy-lyrics.js", import.meta.url);
// Never package a stale build if the creator reports success after an error.
rmSync(output, { force: true });
const build = spawnSync(process.execPath, [
  "node_modules/@spicemod/creator/dist/bin.mjs", "build", "--no-copy",
], { cwd: root, stdio: "inherit" });
if (build.error) throw build.error;
if (build.status !== 0) throw new Error(`Build failed: ${build.status}`);
const code = readFileSync(output, "utf8");
// Syntax validation catches a truncated output before it replaces the installer.
const check = spawnSync(process.execPath, ["--check", fileURLToPath(output)], { stdio: "inherit" });
if (check.status !== 0) throw new Error("Invalid build output");
for (const marker of ["sl-lyrics-share", "neteaseFallback", "lineOnlyLyrics", "ChrisTeng97/spicy-lyrics"]) {
  if (!code.includes(marker)) throw new Error(`Missing fork feature: ${marker}`);
}
if (code.includes("grabPluginFile")) throw new Error("Upstream plugin loader found in bundle");
const destination = new URL("../builds/spicy-lyrics.mjs", import.meta.url);
writeFileSync(destination, "// ChrisTeng97/spicy-lyrics — standalone fork build; generated by npm run build:fork.\n" + code);
console.log(`Packaged ${Buffer.byteLength(code)} bytes into builds/spicy-lyrics.mjs`);
